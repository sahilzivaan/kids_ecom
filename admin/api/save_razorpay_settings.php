<?php
header('Content-Type: application/json');
require_once '../includes/auth.php'; // Ensure only admin can access this

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    http_response_code(405);
    echo json_encode(['error' => 'Method Not Allowed']);
    exit;
}

$input = json_decode(file_get_contents('php://input'), true);

if (!isset($input['key_id']) || !isset($input['key_secret'])) {
    http_response_code(400);
    echo json_encode(['error' => 'Missing Razorpay credentials']);
    exit;
}

$key_id = trim($input['key_id']);
$key_secret = trim($input['key_secret']);

// Validate that keys are not empty
if (empty($key_id) || empty($key_secret)) {
    http_response_code(400);
    echo json_encode(['error' => 'Keys cannot be empty']);
    exit;
}

// Generate the new content for razorpay_config.php
$config_content = "<?php\n";
$config_content .= "// includes/razorpay_config.php\n";
$config_content .= "// Auto-generated by Admin Settings\n\n";
$config_content .= "define('RAZORPAY_KEY_ID', '" . addslashes($key_id) . "');\n";
$config_content .= "define('RAZORPAY_KEY_SECRET', '" . addslashes($key_secret) . "');\n\n";
$config_content .= "?>";

$config_path = __DIR__ . '/../includes/razorpay_config.php';

// Write the file
if (file_put_contents($config_path, $config_content) !== false) {
    echo json_encode(['success' => true, 'message' => 'Razorpay credentials saved successfully.']);
} else {
    http_response_code(500);
    echo json_encode(['error' => 'Failed to write configuration file. Please check file permissions.']);
}
?>
